import { describe, expect, it } from 'vitest';
import { plainEndingsIn } from './plainEnding';

/**
 * 문체 검사의 양성 대조. 표본은 문체를 맞추기 전의 프로덕션 화면에 있던 문구다 — 이 검사가 그것들을 잡아야 화면 검사의 빈
 * 결과가 "그런 문장이 없다" 를 뜻한다(sp-docs/process/review-policy.md §4.1).
 */
describe('문체 검사', () => {
  it.each([
    ['쓸 수 있는 이메일이다', '이메일이다'],
    ['이미 쓰이고 있는 닉네임이다', '닉네임이다'],
    ['나중에 등록해도 된다 — 프로필이 없으면 글과 댓글만 쓸 수 없다.', '된다'],
    ['댓글이 없다', '없다'],
    ['작성에는 프로필이 필요하다', '필요하다'],
    ['0 / 200 · 공백만으로 채울 수 없다', '없다'],
    ['프로필이 아니다.', '아니다'],
    ['기다려야 한다!', '한다'],
    ['이미 있다, 다른 값을', '있다'],
  ])('"%s" 를 잡는다', (text, word) => {
    expect(plainEndingsIn(text)).toContain(word);
  });

  it('줄마다 본다 — 화면 문구는 텍스트 노드마다 한 줄이다', () => {
    expect(plainEndingsIn('게시판\n쓴 글이 없다\n로그인')).toEqual(['없다']);
  });

  it.each([
    '게시글을 찾을 수 없습니다.',
    '글과 댓글을 쓰려면 프로필을 먼저 등록해야 합니다.',
    '입력한 내용을 확인해 주세요.',
    '잠시 후 다시 시도해 주세요.',
    '다시 시도',
    '다음',
    '닉네임 수정 완료',
    '계정이 없으면 가입.',
    '댓글을 쓰려면 로그인',
    '불러오는 중…',
    '탈퇴한 회원',
    '다른 이메일로 새 계정을 만들어 주세요.',
  ])('"%s" 는 잡지 않는다', (text) => {
    expect(plainEndingsIn(text)).toEqual([]);
  });
});
