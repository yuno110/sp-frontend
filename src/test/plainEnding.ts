/**
 * 문장이 「~다」 체로 끝나는 문구를 잡는다. 프로덕션 화면의 문장은 「~다」 체로 끝내지 않는다(CLAUDE.md 「화면 문구와 오류 표시」).
 *
 * 문장의 끝은 줄 끝, 문장 부호와 쉼표, 줄표(`—`) 앞이다. 「다시」·「다음」처럼 낱말 앞머리의 `다` 는 뒤에 글자가 이어져 걸리지
 * 않는다. 「아니다」 는 끝이 「니다」 지만 「~다」 체다. 표본은 plainEnding.test.ts 가 본다 — 아무것도 잡지 못하는 패턴은
 * "걸리는 것이 없다" 를 패턴이 틀려도 낸다.
 *
 * 화면에 사용자가 쓴 값도 함께 지나간다(예: 제목 「바다」). 그래서 이 검사는 테스트가 정한 값으로 그린 화면에만 쓴다.
 */
const PLAIN_ENDING = /[가-힣]*(?:(?<!니)|(?<=아니))다(?=\s*(?:[.!?,—]|$))/gm;

/** 「~다」 로 끝나는 낱말들. 없으면 빈 배열이다. */
export function plainEndingsIn(text: string): string[] {
  return [...text.matchAll(PLAIN_ENDING)].map((m) => m[0]);
}
